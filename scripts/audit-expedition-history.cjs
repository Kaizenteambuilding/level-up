const assert = require('node:assert/strict')
const fs = require('node:fs')
const shell = fs.readFileSync('components/DemoGameShell.tsx', 'utf8')
const journal = fs.readFileSync('components/DemoAchievements.tsx', 'utf8')
assert.ok(shell.includes("select('session_id,correct')"), 'Expedition history does not load persisted answers')
assert.ok(shell.includes('correctBySession[mission.id] ?? 0'), 'Persisted answers are not joined to their mission')
assert.ok(shell.includes(".eq('completed', true).eq('phase', 'done')"), 'History includes unverified sessions')
assert.ok(journal.includes('Registro sincronizado'), 'Journal does not explain its server-backed history')
assert.ok(!journal.includes('Registro local'), 'Journal still claims to be local-only')
console.log('Expedition history audit passed.')
