const assert = require('node:assert/strict')
const fs = require('node:fs')
const shell = fs.readFileSync('components/DemoGameShell.tsx', 'utf8')
const onboarding = fs.readFileSync('components/GameOnboarding.tsx', 'utf8')
const missionGuard = fs.readFileSync('components/MissionGuard.tsx', 'utf8')
const completion = fs.readFileSync('database/migrations/20260824082216_add_account_onboarding.sql', 'utf8')
