const assert = require('node:assert/strict')
const fs = require('node:fs')
const baseMigration = fs.readFileSync('database/migrations/20260824095609_add_game_summary_rpc.sql', 'utf8')
const metricsMigration = fs.readFileSync('database/migrations/20260901141000_fix_game_summary_metrics.sql', 'utf8')
const shell = fs.readFileSync('components/DemoGameShell.tsx', 'utf8')

assert.ok(baseMigration.includes('revoke execute'), 'Summary RPC is not permission-bound')
assert.ok(metricsMigration.includes("ss.completed = true") && metricsMigration.includes("ss.phase = 'done'"), 'Summary includes incomplete activities')
assert.ok(metricsMigration.includes("'total_missions', coalesce(v_total_activities, 0)"), 'Legacy total_missions must now mean completed activities')
assert.ok(metricsMigration.includes("'total_activities', coalesce(v_total_activities, 0)"), 'Summary must expose total activities')
assert.ok(metricsMigration.includes("'total_daily_expeditions', coalesce(v_total_daily_expeditions, 0)"), 'Summary must expose daily expeditions')
assert.ok(metricsMigration.includes("'active_days', coalesce(v_active_days, 0)"), 'Summary must expose active days')
assert.ok(metricsMigration.includes("at time zone 'Europe/Madrid'"), 'Activity days and streak need the explicit product timezone')
assert.ok(metricsMigration.includes('pp.id = auth.uid()'), 'Summary RPC does not verify ownership')
assert.ok(shell.includes("rpc('get_levelup_game_summary'"), 'Game shell does not load the server summary')
assert.ok(shell.includes('player.totalMissions'), 'World does not display the authoritative activity total')
assert.ok(shell.includes('player.streakDays'), 'HUD does not display the streak')
console.log('Game summary audit passed.')