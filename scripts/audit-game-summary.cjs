const assert = require('node:assert/strict')
const fs = require('node:fs')
const baseMigration = fs.readFileSync('database/migrations/20260824095609_add_game_summary_rpc.sql', 'utf8')
const distinctMigration = fs.readFileSync('database/migrations/20260824173000_count_distinct_daily_missions.sql', 'utf8')
const shell = fs.readFileSync('components/DemoGameShell.tsx', 'utf8')
assert.ok(baseMigration.includes("completed = true and ss.phase = 'done'"), 'Summary includes incomplete missions')
assert.ok(distinctMigration.includes("count(distinct (ss.ended_at at time zone 'Europe/Madrid')::date)"), 'Total missions must count one completed mission per calendar day')
assert.ok(distinctMigration.includes("at time zone 'Europe/Madrid'"), 'Mission totals and streak need the explicit product timezone')
assert.ok(distinctMigration.includes('pp.id = auth.uid()'), 'Summary RPC does not verify ownership')
assert.ok(distinctMigration.includes('revoke execute'), 'Summary RPC is not permission-bound')
assert.ok(shell.includes("rpc('get_levelup_game_summary'"), 'Game shell does not load the server summary')
assert.ok(shell.includes('player.totalMissions'), 'World does not display the authoritative mission total')
assert.ok(shell.includes('player.streakDays'), 'HUD does not display the streak')
console.log('Game summary audit passed.')
